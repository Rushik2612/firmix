#!/usr/bin/env python3
"""
make_plan.py -- assign neutral slot names (f001..f050) to the benchmark.

Why: file names must not reveal the bug type (an LLM that sees "int01_..." in a
path has been told the answer). Slots are assigned by a SEEDED shuffle, so the
mapping is reproducible but not guessable from the name or the order.

Writes benchmark/PLAN.md. You write files per bug type (efficient), but name
each file with the slot listed for it.  Run once; do not re-run after you
start writing files unless you also delete the plan (the seed fixes the output).
"""
import random
from pathlib import Path

SEED = 1026
BUG_TYPES = ["INT-01", "INT-02", "INT-03", "RTOS-01", "RTOS-02", "RTOS-03",
             "PER-01", "PER-02", "MEM-01", "MEM-02"]
PER_TYPE = 4

# test set: 40 buggy (4 per type) + 10 clean (one near-miss per type)
slots = [(t, "buggy") for t in BUG_TYPES for _ in range(PER_TYPE)]
slots += [(t, "clean") for t in BUG_TYPES]
rng = random.Random(SEED)
rng.shuffle(slots)
assign = {f"f{i+1:03d}": s for i, s in enumerate(slots)}

lines = ["# Benchmark plan (generated by tools/make_plan.py, seed %d)\n" % SEED,
         "Write each file under the slot name shown. Bug type per slot is below;",
         "keep this file private -- it is the answer key's index.\n",
         "| Bug type | Buggy slots (4) | Clean near-miss slot (1) |", "|---|---|---|"]
for t in BUG_TYPES:
    b = sorted(k for k, v in assign.items() if v == (t, "buggy"))
    c = sorted(k for k, v in assign.items() if v == (t, "clean"))
    lines.append(f"| {t} | {', '.join(b)} | {', '.join(c)} |")
lines += ["", "## Dev set (not scored; use these to write rules and prompts)", "",
          "d01..d12 are already written: 10 buggy (one per bug type) + 2 clean near-misses.",
          "Their answers are in benchmark/ground_truth.json. Do not add more test files to benchmark/dev."]
Path("benchmark/PLAN.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
